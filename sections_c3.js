window.updateAsignaturas = function() {
    const comp = document.getElementById('compSelector').value;
    const asigSel = document.getElementById('asigSelector');
    asigSel.innerHTML = '<option value="">-- Seleccione una Asignatura --</option>';
    
    if (comp && window.trazabilidadData[comp]) {
        Object.keys(window.trazabilidadData[comp]).forEach(asig => {
            const opt = document.createElement('option');
            opt.value = asig;
            opt.textContent = asig;
            asigSel.appendChild(opt);
        });
    }
    document.getElementById('ra_asig').textContent = '-';
    document.getElementById('ra_prog').textContent = '-';
};

window.showDetails = function() {
    const comp = document.getElementById('compSelector').value;
    const asig = document.getElementById('asigSelector').value;
    if (comp && asig && window.trazabilidadData[comp][asig]) {
        document.getElementById('ra_asig').textContent = window.trazabilidadData[comp][asig].asig;
        document.getElementById('ra_prog').textContent = window.trazabilidadData[comp][asig].prog;
    }
};

window.changeTab = function(tabId) {
    document.querySelectorAll('.tab-content').forEach(c => c.classList.add('hidden'));
    document.querySelectorAll('.tab-btn').forEach(b => b.classList.remove('active', 'border-toOrange', 'text-toOrange'));
    document.getElementById(tabId).classList.remove('hidden');
    event.currentTarget.classList.add('active', 'border-toOrange', 'text-toOrange');
};

